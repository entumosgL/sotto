"""Профиль кандидата — Markdown, который ты пишешь сам. Незаполненный шаблон считается пустым:
иначе модель копирует из него заглушки «…»."""

from __future__ import annotations

TEMPLATE = """\
# Профиль кандидата

## Цель
Роль: …  Уровень: …  Формат: удалёнка/офис, город, зарплатная вилка: …

## Стек
Уверенно: …
Работал: …

## Опыт
### Компания — роль (годы)
- Проект: что делали, масштаб (RPS, данные, команда), мой вклад, результат в цифрах

## Образование

## Языки
Английский: уровень …

## Что важно в работе
"""


def is_filled(text: str) -> bool:
    norm = lambda t: " ".join(t.split())  # noqa: E731
    return bool(text.strip()) and norm(text) != norm(TEMPLATE)
